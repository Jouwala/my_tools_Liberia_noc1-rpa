interface I18nContextType {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, params?: Record<string, string | number>) => string
  toggleLocale: () => void
}

const I18nContext = createContext<I18nContextType>({
  locale: 'zh',
  setLocale: () => {},
  t: (key: string) => key,
  toggleLocale: () => {},
})

function detectLocale(): Locale {
  const saved = localStorage.getItem('app-locale')
  if (saved === 'zh' || saved === 'en') return saved
  const lang = navigator.language || (navigator as any).userLanguage || 'zh'
  return lang.startsWith('zh') ? 'zh' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale)

  // 语言变化时同步给后端（任务名等数据字段需要按语言返回），
  // 并同步文档语言（页面标题由 AppContent 按当前页面动态设置，避免被父级覆写）
  useEffect(() => {
    setApiLocale(locale)
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en'
    // 同步语言给嵌入的 legacy HTML 工具（同源 iframe，如 Alarm Management 看板）
    try {
      document.querySelectorAll('iframe').forEach((f) => {
        f.contentWindow?.postMessage({ __type: 'myapp-locale', locale }, '*')
      })
    } catch (e) { /* ignore */ }
  }, [locale])

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l)
    localStorage.setItem('app-locale', l)
  }, [])

  const toggleLocale = useCallback(() => {
    setLocale(locale === 'zh' ? 'en' : 'zh')
  }, [locale, setLocale])

  const t = useCallback((key: string, params?: Record<string, string | number>) => {
    let text = translations[locale]?.[key] || translations['zh']?.[key] || key
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, String(v))
      })
    }
    return text
  }, [locale])

  return (
    <I18nContext.Provider value={{ locale, setLocale, t, toggleLocale }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  return useContext(I18nContext)
}
